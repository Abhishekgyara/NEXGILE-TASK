import { useMemo, useState } from 'react';
import { Download } from 'lucide-react';
import { Badge, Button, Card, Column, DataTable, FilterSelect, SearchInput, useDebounced } from '@/components/ui';
import { useStore } from '@/lib/store';
import { dateTime, num } from '@/lib/format';
import { buildLogsCsv } from '@/lib/reports';
import type { WorkerLog } from '@/lib/types';

export function WorkerLogsPage() {
  const { world, recentLogs, pushToast } = useStore();
  const [search, setSearch] = useState('');
  const debounced = useDebounced(search);
  const [workerFilter, setWorkerFilter] = useState('ALL');
  const [levelFilter, setLevelFilter] = useState('ALL');

  const counts = useMemo(() => {
    const errors = world.workerLogs.filter((l) => l.level === 'ERROR').length;
    const warns = world.workerLogs.filter((l) => l.level === 'WARN').length;
    return { total: world.workerLogs.length, errors, warns };
  }, [world]);

  const filtered = useMemo(() => {
    const q = debounced.trim().toLowerCase();
    return recentLogs.filter((l) => {
      if (workerFilter !== 'ALL' && l.workerId !== workerFilter) return false;
      if (levelFilter !== 'ALL' && l.level !== levelFilter) return false;
      if (q) {
        const hay = `${l.refundId ?? ''} ${l.event} ${l.message}`.toLowerCase();
        if (!hay.includes(q)) return false;
      }
      return true;
    });
  }, [recentLogs, debounced, workerFilter, levelFilter]);

  const columns: Column<WorkerLog>[] = [
    { key: 'worker', header: 'Worker ID', render: (l) => <span className="font-medium text-slate-700">{l.workerId}</span>, sortValue: (l) => l.workerId },
    { key: 'time', header: 'Timestamp', render: (l) => <span className="text-xs text-slate-500 tabular">{dateTime(l.createdAt)}</span>, sortValue: (l) => l.createdAt },
    { key: 'refund', header: 'Refund ID', render: (l) => l.refundId ?? '—' },
    { key: 'level', header: 'Level', render: (l) => <Badge value={l.level} /> },
    { key: 'event', header: 'Event', render: (l) => <span className="text-slate-700">{l.event}</span> },
    { key: 'status', header: 'Status', render: (l) => <Badge value={l.status} /> },
    {
      key: 'message',
      header: 'Error Message',
      render: (l) => (
        <span className={`text-xs ${l.level === 'ERROR' ? 'text-rose-700 bg-rose-50 rounded px-1.5 py-0.5' : l.level === 'WARN' ? 'text-amber-700 bg-amber-50 rounded px-1.5 py-0.5' : 'text-slate-500'}`}>
          {l.message}
        </span>
      ),
    },
  ];

  const downloadCsv = () => {
    const blob = new Blob([buildLogsCsv(filtered)], { type: 'text/csv' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'worker-logs.csv';
    a.click();
    URL.revokeObjectURL(url);
    pushToast('success', `${num(filtered.length)} log entries downloaded as CSV`);
  };

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-xl font-semibold text-slate-900">Worker Logs</h1>
          <p className="text-sm text-slate-500 mt-0.5">Generated by actual worker operations: job claims, provider calls, ledger writes, crashes, and retries.</p>
        </div>
        <Button variant="secondary" onClick={downloadCsv}><Download size={15} /> Export CSV</Button>
      </div>

      <div className="grid grid-cols-3 gap-4">
        <Card className="card-hover p-5">
          <p className="text-xs font-medium text-slate-500 uppercase tracking-wide">Total log entries</p>
          <p className="mt-2 text-2xl font-semibold text-slate-900 tabular">{num(counts.total)}</p>
        </Card>
        <Card className="card-hover p-5">
          <p className="text-xs font-medium text-slate-500 uppercase tracking-wide">Error entries</p>
          <p className="mt-2 text-2xl font-semibold text-rose-700 tabular">{num(counts.errors)}</p>
        </Card>
        <Card className="card-hover p-5">
          <p className="text-xs font-medium text-slate-500 uppercase tracking-wide">Warning entries</p>
          <p className="mt-2 text-2xl font-semibold text-amber-700 tabular">{num(counts.warns)}</p>
        </Card>
      </div>

      <Card>
        <div className="flex flex-wrap items-center gap-3 px-5 py-4 border-b border-slate-100">
          <SearchInput value={search} onChange={setSearch} placeholder="Search by refund ID, event, or message…" />
          <FilterSelect label="Worker" value={workerFilter} onChange={setWorkerFilter} options={[
            { value: 'ALL', label: 'All workers' },
            ...['worker-01', 'worker-02', 'worker-03', 'worker-04'].map((w) => ({ value: w, label: w })),
          ]} />
          <FilterSelect label="Severity" value={levelFilter} onChange={setLevelFilter} options={[
            { value: 'ALL', label: 'All severities' },
            { value: 'INFO', label: 'Info' },
            { value: 'WARN', label: 'Warning' },
            { value: 'ERROR', label: 'Error' },
          ]} />
          <span className="ml-auto text-xs text-slate-500">{filtered.length} entries</span>
        </div>
        <DataTable columns={columns} rows={filtered} rowKey={(l) => l.id} pageSize={15} />
      </Card>
    </div>
  );
}
